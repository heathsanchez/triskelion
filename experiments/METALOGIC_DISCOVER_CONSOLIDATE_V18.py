import os,json,importlib.util
from pathlib import Path
import river_client as river

# Execute/reuse the already frozen verified composer. This independently establishes retrieval and explicit composition first.
spec=importlib.util.spec_from_file_location('v16','experiments/METALOGIC_VERIFIED_COMPOSER_V16.py');v16=importlib.util.module_from_spec(spec);spec.loader.exec_module(v16)
OUT=Path('artifacts/discover_consolidate_v18');OUT.mkdir(parents=True,exist_ok=True)
BASE=v16.BASE;SEED=v16.SEED;TH=0.75;LR=5e-5;MAX_STEPS=6;EOS=v16.tok.eos_token_id
TRAIN=list(range(16))

def plan_text(plan): return ';'.join(f'{op}@{idx}' for op,idx in plan)
def verified_plan_on(key,k,plan):
    name,mut,_=v16.variant(key,k)
    try: fixed=v16.repair(mut,name,plan)
    except: return False
    return v16.run_source(name,fixed,v16.tests_for(name))[0]
def datum_from_plan(key,k,plan):
    assert verified_plan_on(key,k,plan),(key,k,plan)
    p=v16.tok(v16.prompt(key,k),add_special_tokens=False)['input_ids']; b=v16.tok(' '+plan_text(plan),add_special_tokens=False)['input_ids']+[EOS]; ids=p+b
    return {'input_ids':ids,'target_tokens':ids[1:]+[EOS],'weights':[0.0]*(len(p)-1)+[1.0]*(len(b)+1)}
def eval_keys(m,keys): return {k:v16.direct_eval(m,k)[0] for k in keys}
def train_until_joint(m,label,batch,keys):
    curve=[]
    for st in range(1,MAX_STEPS+1):
        fb=m.forward_backward(batch,loss_fn='cross_entropy');m.optim_step(lr=LR,grad_clip_norm=1.0)
        scores=eval_keys(m,keys);joint=min(scores.values());row={'step':st,'loss':float(fb.metrics['loss']),'scores':scores,'joint':joint};curve.append(row);print(json.dumps({'stage':label,**row}),flush=True)
        if joint>=TH:
            ck=m.save_weights(f'v18_{label}_step{st}',mode='training').path;return curve,ck,st
    ck=m.save_weights(f'v18_{label}_final',mode='training').path;return curve,ck,None

def reload_scores(ck,keys,label):
    with v16.client.session(project='ml-v18-reload-'+label) as s:
        m=s.create_model(base_model=BASE,lora=river.LoraConfig(rank=32,seed=SEED),checkpoint=ck);return eval_keys(m,keys)

R={'source_checkpoint':v16.CHECKPOINT,'v16_verdict':v16.R['verdict'],'stages':{},'generated_supervision':{}}
# Explicitly discover D=A+B from the retained primitive graph.
ab_score,ab_rows=v16.compose_target('AB_TEST',v16.plans)
passing=[r['chosen'] for r in ab_rows if r['protected_pass'] and r['chosen']]
assert ab_score>=TH and passing
D=passing[0]['plan'];assert all(x['plan']==D for x in passing)
R['generated_supervision']['D']={'plan':D,'heldout_explicit_score':ab_score,'train_verified':all(verified_plan_on('AB_TEST',k,D) for k in TRAIN)}
assert R['generated_supervision']['D']['train_verified']
# Consolidate D into weights. Composite labels are generated by the verified composer, not hand-authored.
with v16.client.session(project='ml-v18-D-consolidate') as s:
    m=s.create_model(base_model=BASE,lora=river.LoraConfig(rank=32,seed=SEED),checkpoint=v16.CHECKPOINT)
    batch=[datum_from_plan('AB_TEST',k,D) for k in TRAIN[:12]]
    batch += [datum_from_plan('A',12,v16.plans['A']),datum_from_plan('B',13,v16.plans['B']),datum_from_plan('C',14,v16.plans['C']),datum_from_plan('A',15,v16.plans['A'])]
    pre=eval_keys(m,['A','B','C','AB_TEST']);curve,ckD,doseD=train_until_joint(m,'D',batch,['A','B','C','AB_TEST'])
postD=reload_scores(ckD,['A','B','C','AB_TEST'],'D')
R['stages']['D']={'pre':pre,'curve':curve,'dose':doseD,'checkpoint':ckD,'post_reload':postD}
if doseD is None or min(postD.values())<TH:
    R['verdict']='FAIL_D_CONSOLIDATION';(OUT/'RESULT.json').write_text(json.dumps(R,indent=2));print(json.dumps(R,indent=2));raise SystemExit
# Explicitly build E from promoted D + retained C; again verifier decides the composition.
hier={'D':D,'C':v16.plans['C']};abc_score,abc_rows=v16.compose_target('ABC_TEST',hier)
passingE=[r['chosen'] for r in abc_rows if r['protected_pass'] and r['chosen']]
assert abc_score>=TH and passingE
Eplan=passingE[0]['plan'];assert all(x['plan']==Eplan for x in passingE)
R['generated_supervision']['E']={'plan':Eplan,'heldout_explicit_score':abc_score,'train_verified':all(verified_plan_on('ABC_TEST',k,Eplan) for k in TRAIN)}
assert R['generated_supervision']['E']['train_verified']
# Consolidate E from the D checkpoint while protecting primitives + D.
with v16.client.session(project='ml-v18-E-consolidate') as s:
    m=s.create_model(base_model=BASE,lora=river.LoraConfig(rank=32,seed=SEED),checkpoint=ckD)
    batch=[datum_from_plan('ABC_TEST',k,Eplan) for k in TRAIN[:11]]
    batch += [datum_from_plan('AB_TEST',11,D),datum_from_plan('AB_TEST',12,D),datum_from_plan('A',13,v16.plans['A']),datum_from_plan('B',14,v16.plans['B']),datum_from_plan('C',15,v16.plans['C'])]
    preE=eval_keys(m,['A','B','C','AB_TEST','ABC_TEST']);curveE,ckE,doseE=train_until_joint(m,'E',batch,['A','B','C','AB_TEST','ABC_TEST'])
postE=reload_scores(ckE,['A','B','C','AB_TEST','ABC_TEST'],'E')
R['stages']['E']={'pre':preE,'curve':curveE,'dose':doseE,'checkpoint':ckE,'post_reload':postE}
R['gates']={
 'explicit_D_discovered':ab_score>=TH,
 'D_supervision_externally_verified':R['generated_supervision']['D']['train_verified'],
 'D_becomes_direct_neural':postD['AB_TEST']>=TH,
 'primitives_survive_D':min(postD[k] for k in ['A','B','C'])>=TH,
 'explicit_E_discovered_from_D_plus_C':abc_score>=TH,
 'E_supervision_externally_verified':R['generated_supervision']['E']['train_verified'],
 'E_becomes_direct_neural':postE['ABC_TEST']>=TH,
 'D_survives_E':postE['AB_TEST']>=TH,
 'primitives_survive_E':min(postE[k] for k in ['A','B','C'])>=TH,
}
R['verdict']='PASS_DISCOVER_VERIFY_CONSOLIDATE_LOOP' if all(R['gates'].values()) else 'MIXED_DISCOVER_VERIFY_CONSOLIDATE_LOOP'
(OUT/'RESULT.json').write_text(json.dumps(R,indent=2));print(json.dumps(R,indent=2),flush=True)
